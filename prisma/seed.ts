async function main() {
  const profile = await db.profile.findFirst();
  if (!profile) {
    throw new Error(
      "❌ ไม่พบ Profile ในระบบ — กรุณา login ก่อนรัน seed แล้วลองใหม่",
    );
  }

  console.log(
    `\n✅ ใช้ Profile: ${profile.firstName} ${profile.lastName} (${profile.clerkId})\n`,
  );

  let total = 0;

  for (const data of seedData) {
    const categoryImages = images[data.category as keyof typeof images];

    for (let i = 0; i < 10; i++) {
      const province = provinces[i]; // 1 landmark ต่อ 1 จังหวัด
      const latOffset = (Math.random() - 0.5) * 0.3;
      const lngOffset = (Math.random() - 0.5) * 0.3;

      await db.landmark.create({
        data: {
          name: data.names[i],
          description: data.descriptions[i],
          category: data.category,
          image: img(categoryImages[i]),
          province: province.name,
          lat: province.lat + latOffset,
          lng: province.lng + lngOffset,
          price: data.price,
          profileId: profile.clerkId,
        },
      });

      total++;
    }

    console.log(`  ✅ [${data.category}] — 10 landmarks created`);
  }

  console.log(`\n🎉 Seed complete! สร้าง ${total} landmarks เรียบร้อย\n`);
}

main()
  .catch(e => {
    console.error("\n❌ Seed failed:", e.message);
    process.exit(1);
  })
  .finally(() => db.$disconnect());
